/**
 * 道具数据定义
 * 3个道具池：金币池、文化池、信仰池
 * 每个池有16个道具
 *
 * 效果类型:
 *  - flat_per_turn: 每回合固定加成
 *  - per_tag: 每个匹配地块的加成 (ignoreWorked=true 时不需要工人)
 *  - yield_percent: 百分比叠乘加成 (5~8%)
 *  - instant: 立即获得资源
 *  - pop_growth: 立即+1人口
 *  - terrain_alias: 地形别名 (fromTag 的地块也视为 toTag)
 *  - per_adjacent_pair: 匹配地块与特定邻居相邻时加成
 *  - convert_yield: 将一种产出转化为另一种
 *
 * 尤里卡时刻触发条件也在此定义
 */

